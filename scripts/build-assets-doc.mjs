// Writes docs/assets.md: every image and video the kiosk expects, its status and
// where to change it. Reads the content files as text, so it needs no build step.
//
//   node scripts/build-assets-doc.mjs
//
// Re-run after changing a link in content/ or adding files to public/media/.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (rel) => fs.readFileSync(path.join(ROOT, rel), "utf8");
const exists = (rel) => fs.existsSync(path.join(ROOT, rel));
const CLIPS = ["exterior-day", "exterior-night", "interior-day", "interior-night"];

/** real | dummy | empty */
function linkStatus(url) {
  if (!url || !url.trim()) return "empty";
  try {
    const host = new URL(url).hostname;
    return host === "example.com" || host.endsWith(".example.com") ? "dummy" : "real";
  } catch {
    return "empty";
  }
}
const STATUS_LABEL = { real: "✅ real", dummy: "⚠️ dummy", empty: "⬜ empty" };
const shortLink = (url) => {
  if (!url) return "—";
  try {
    const u = new URL(url);
    const name = decodeURIComponent(u.pathname.split("/").pop());
    return `${u.hostname} … \`${name}\``;
  } catch {
    return url;
  }
};

// --- Models (slug, name) in rail order
const models = [...read("content/models.ts").matchAll(/model\("([a-z0-9-]+)", "([^"]+)"/g)].map((m) => ({ slug: m[1], name: m[2] }));

// --- Experience clip links
const videoSrc = read("content/model-videos.ts");
const clipLinks = {};
for (const { slug } of models) {
  const block = new RegExp(`"${slug}": \\{([\\s\\S]*?)\\}`).exec(videoSrc)?.[1] ?? "";
  clipLinks[slug] = Object.fromEntries(CLIPS.map((c) => [c, new RegExp(`"${c}": "([^"]*)"`).exec(block)?.[1] ?? ""]));
}

// --- Home video links
const siteSrc = read("content/site-videos.ts");
const siteLinks = [...siteSrc.matchAll(/^\s+(\w+): "([^"]*)",/gm)].map((m) => ({ key: m[1], url: m[2] }));

// --- Local images
const localList = new Set([...read("content/local-media.ts").matchAll(/"([^"]+\.(?:webp|png|jpg))"/g)].map((m) => m[1]));
const expectedLocal = [
  { path: "home/chassis.webp", use: "02 Home – interactive chassis" },
  { path: "home/blade-battery.webp", use: "02 Home – Blade Battery poster / fallback" },
  ...models.flatMap(({ slug, name }) => [
    { path: `models/${slug}/${slug}-cutout.webp`, use: `${name} – cut-out (Models, Experience fallback, line-up)` },
    { path: `models/${slug}/${slug}-thumb.webp`, use: `${name} – rail thumbnail` },
    ...[1, 2, 3, 4].map((i) => ({ path: `models/${slug}/${slug}-gallery-${i}.webp`, use: `${name} – gallery ${i}` })),
  ]),
];

// --- Counts
const allClipLinks = models.flatMap(({ slug }) => CLIPS.map((c) => clipLinks[slug][c]));
const count = (links, status) => links.filter((l) => linkStatus(l) === status).length;
const siteUrls = siteLinks.map((s) => s.url);
const localOk = expectedLocal.filter((e) => localList.has(e.path) && exists(`public/media/${e.path}`)).length;

const lines = [];
const out = (s = "") => lines.push(s);

out("# Media assets");
out();
out("_Generated by `node scripts/build-assets-doc.mjs` – do not edit by hand; re-run it after changing links or files._");
out();
out("## Summary");
out();
out("| Group | Real | Dummy | Empty | Where to change |");
out("| --- | --- | --- | --- | --- |");
out(`| Experience videos (9 models × 4) | ${count(allClipLinks, "real")} | ${count(allClipLinks, "dummy")} | ${count(allClipLinks, "empty")} | \`content/model-videos.ts\` |`);
out(`| Home videos | ${count(siteUrls, "real")} | ${count(siteUrls, "dummy")} | ${count(siteUrls, "empty")} | \`content/site-videos.ts\` |`);
out(`| Local images | ${localOk} of ${expectedLocal.length} present | – | ${expectedLocal.length - localOk} missing | \`public/media/\` + \`content/local-media.ts\` |`);
out();
out("- **Real** links are downloaded for offline use on first launch (once the bucket's CORS rule is set – see `docs/kiosk-setup.md`).");
out("- **Dummy** links (`example.com`) never load: visitors see the car cut-out (Experience) or the fallback image / logo (Home) instead. Links are never shown on screen; add `?debug=1` to the address to see slot labels.");
out("- After replacing links, bump `contentVersion` in `content/site-settings.ts` so kiosks download the new videos and delete the old ones.");
out("- Video format: MP4 (H.264), 1920 × 1080, muted, short seamless loop (~10–20 s).");
out();
out("## Experience videos");
out();
out("| Model | Exterior · Day | Exterior · Night | Interior · Day | Interior · Night |");
out("| --- | --- | --- | --- | --- |");
for (const { slug, name } of models) {
  out(`| ${name} | ${CLIPS.map((c) => STATUS_LABEL[linkStatus(clipLinks[slug][c])]).join(" | ")} |`);
}
out();
out("## Home videos");
out();
out("| Slot | Status | Link | Fallback while loading / if it fails |");
out("| --- | --- | --- | --- |");
const fallback = { heroShowreel: "BYD logo on dark", bladeBattery: "`home/blade-battery.webp`" };
for (const { key, url } of siteLinks) {
  out(`| \`${key}\` | ${STATUS_LABEL[linkStatus(url)]} | ${linkStatus(url) === "real" ? shortLink(url) : "—"} | ${fallback[key] ?? "—"} |`);
}
out();
out("## Local images (ship with the app)");
out();
out("| File (`public/media/…`) | Used for | Status |");
out("| --- | --- | --- |");
for (const e of expectedLocal) {
  const listed = localList.has(e.path);
  const onDisk = exists(`public/media/${e.path}`);
  const status = listed && onDisk ? "✅" : onDisk ? "⚠️ on disk, not listed" : listed ? "❌ listed, file missing" : "❌ missing";
  out(`| \`${e.path}\` | ${e.use} | ${status} |`);
}
out();
out("## Other files");
out();
out("| File | Used for | Made by |");
out("| --- | --- | --- |");
out("| `public/brand/byd-logo-white.png`, `byd-logo-black.png` | Logo everywhere | supplied, cleaned up |");
out("| `public/icons/*.png`, `app/icon.png` | App icons, browser tab | `node scripts/build-icons.mjs` |");
out("| `assets/og/<model>.png` | Link-preview images (car cut-outs as PNG) | `node scripts/build-icons.mjs` |");
out("| `assets/fonts/Michroma-Regular.ttf` | Link-preview images font (SIL OFL, see `OFL.txt`) | Google Fonts |");
const unused = fs.existsSync(path.join(ROOT, "public/media/battery")) ? fs.readdirSync(path.join(ROOT, "public/media/battery")) : [];
if (unused.length) {
  out();
  out(`> **Unused originals:** \`public/media/battery/\` (${unused.join(", ")}) are the source files for the Home images. They are not used by the app but are still deployed; move them out of \`public/\` to save space.`);
}
out();

fs.writeFileSync(path.join(ROOT, "docs/assets.md"), lines.join("\n"));
console.log(`docs/assets.md: ${models.length} models, ${allClipLinks.length} clips (${count(allClipLinks, "real")} real), ${siteLinks.length} home videos, ${localOk}/${expectedLocal.length} local images`);
